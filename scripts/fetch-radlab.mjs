#!/usr/bin/env node
// Builds src/sim/outpost/radlab.ts from NASA OSDR RadLab.
// Usage: node scripts/fetch-radlab.mjs [--cache DIR]
// With --cache, reads DIR/rad_msl.csv and DIR/rad_iss.csv instead of downloading them.
import { readFileSync, writeFileSync } from 'node:fs'

const API = 'https://visualization.osdr.nasa.gov/radlab/api/'
const QUERIES = {
  msl: 'instrument_id=MSL-RAD-Surface&timestamp>=2024-05-01&timestamp<2024-06-01&absorbed_dose_rate&format=csv',
  iss: 'instrument_id=DosTel1&timestamp>=2024-05-01&timestamp<2024-06-01&absorbed_dose_rate&format=csv',
}
const cacheIndex = process.argv.indexOf('--cache')
const cache = cacheIndex > 0 ? process.argv[cacheIndex + 1] : null

async function rows(id) {
  const text = cache ? readFileSync(`${cache}/rad_${id}.csv`, 'utf8') : await (await fetch(API + '?' + QUERIES[id])).text()
  return text.trim().split('\n').slice(1).map(line => {
    const [time, , rate] = line.split(',')
    return { time: time.replaceAll('"', ''), rate: Number(rate) }
  }).filter(row => Number.isFinite(row.rate))
}
const round = (n, d = 2) => Math.round(n * 10 ** d) / 10 ** d
const mean = list => list.reduce((a, b) => a + b, 0) / list.length
const median = list => { const s = [...list].sort((a, b) => a - b); return s[Math.floor(s.length / 2)] }
function daily(list) {
  const days = new Map()
  for (const row of list) {
    const day = row.time.slice(0, 10)
    days.set(day, [...(days.get(day) ?? []), row.rate])
  }
  return [...days].map(([date, values]) => ({ date, mean: round(mean(values)), max: round(Math.max(...values)) }))
}

const msl = await rows('msl'), iss = await rows('iss')
const storm = msl.filter(row => row.time.startsWith('2024-05-20'))
const hourly = Array.from({ length: 24 }, (_, h) => round(mean(storm.filter(row => Number(row.time.slice(11, 13)) === h).map(row => row.rate)), 1))
const quiet = msl.filter(row => !row.time.startsWith('2024-05-20') && !row.time.startsWith('2024-05-21')).map(row => row.rate)
const out = {
  source: 'NASA OSDR RadLab Data API',
  url: 'https://visualization.osdr.nasa.gov/radlab/gui/data-api/',
  retrieved: new Date().toISOString().slice(0, 10),
  unit: 'µGy/h (absorbed dose rate)',
  mars: { instrument: 'MSL-RAD-Surface', spacecraft: 'Curiosity', site: 'Gale Crater', quietMean: round(mean(quiet)), stormDate: '2024-05-20', stormHourly: hourly, nextDayMean: daily(msl).find(d => d.date === '2024-05-21').mean, daily: daily(msl) },
  iss: { instrument: 'DosTel1', spacecraft: 'ISS', median: round(median(iss.map(r => r.rate))), mean: round(mean(iss.map(r => r.rate))), daily: daily(iss) },
}
writeFileSync(new URL('../src/sim/outpost/radlab.ts', import.meta.url),
  '// Generated by scripts/fetch-radlab.mjs. Do not edit by hand.\nexport const RADLAB = ' + JSON.stringify(out) + ' as const\n')
console.log('Mars quiet', out.mars.quietMean, 'storm peak hour', Math.max(...hourly), 'ISS median', out.iss.median)
